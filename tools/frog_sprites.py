#!/usr/bin/env python3
"""The sprite images of the C64 Enhanced version (V2 frog, V3 fly; docs/enhanced_graphics.md).

  python3 tools/frog_sprites.py            write c64/src/sprites.inc

The frog is drawn from the game's own graphics (frog_gfx, the four directions, and splat_gfx), read from the Oric
tape and widened to 8 pixels a character as the port shows them, so the sprite has the character frog's shape. Each
frame is two sprites: a multicolour body (green, with light green and a yellow top edge, the V1 lane recipe) and a
hires black outline one pixel round it. The fly is the two-frame drawing of the mock-ups: a black body and light grey
wings, one hires sprite each. 64 bytes a sprite, in VIC block order from $8400 (block 16). Needs the build's label
file (`make`) for the graphics' addresses; standard library only besides docs/tools/render_enhanced.py's helpers.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(ROOT, 'docs', 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import oric_screens  # noqa: E402
from render_enhanced import FLY, glyph_at, labels, to_mc  # noqa: E402

INC = os.path.join(ROOT, 'c64', 'src', 'sprites.inc')

# to_mc values -> multicolour sprite bit pairs: 1 half -> 01 ($D025), 2 edge -> 11 ($D026), 3 full -> 10 ($D027+n)
MC_PAIR = {0: 0b00, 1: 0b01, 2: 0b11, 3: 0b10}


def blank():
    return [[0] * 24 for _ in range(21)]


def to_bytes(grid):
    out = []
    for row in grid:
        for b in range(3):
            out.append(sum(row[b * 8 + i] << (7 - i) for i in range(8)))
    return out + [0]


def bitmap16(glyphs):
    """Four 8x8 glyphs (TL, TR, BL, BR) -> 16x16."""
    return [[glyphs[(0 if y < 8 else 2) + (1 if x >= 8 else 0)][y & 7][x & 7] for x in range(16)] for y in range(16)]


def body_and_outline(bm):
    mc = to_mc(bm)
    body = blank()
    for y in range(16):
        for p in range(8):
            pair = MC_PAIR[mc[y][p]]
            body[y][2 * p] = pair >> 1
            body[y][2 * p + 1] = pair & 1

    def filled(y, x):
        return 0 <= y < 16 and 0 <= x < 16 and mc[y][x >> 1] > 0
    outline = blank()                                   # drawn 1 pixel up and left of the body
    for y in range(-1, 17):
        for x in range(-1, 17):
            if not filled(y, x) and (filled(y - 1, x) or filled(y + 1, x) or filled(y, x - 1) or filled(y, x + 1)):
                outline[y + 1][x + 1] = 1
    return to_bytes(body), to_bytes(outline)


def fly(frame):
    bodyg, wings = blank(), blank()
    for y, row in enumerate(FLY[frame]):
        for x, ch in enumerate(row):
            if ch in 'kr':
                bodyg[y][x + 2] = 1
            elif ch == 'w':
                wings[y][x + 2] = 1
    return to_bytes(bodyg), to_bytes(wings)


def main():
    lab = labels()
    tap = oric_screens.load()
    blocks = []                                         # (name, 64 bytes)
    names = ('up', 'down', 'left', 'right')
    for d, name in enumerate(names):
        bm = bitmap16([glyph_at(tap, lab['frog_gfx'] + d * 32 + k * 8) for k in range(4)])
        b, o = body_and_outline(bm)
        blocks += [('frog %s body' % name, b), ('frog %s outline' % name, o)]
    bm = bitmap16([glyph_at(tap, lab['splat_gfx'] + k * 8) for k in range(4)])
    b, o = body_and_outline(bm)
    blocks += [('splat body', b), ('splat outline', o)]
    for f in range(2):
        b, w = fly(f)
        blocks += [('fly %d body' % f, b), ('fly %d wings' % f, w)]
    lines = ['; c64/src/sprites.inc - generated by tools/frog_sprites.py: do not edit.',
             '; Enhanced sprites (V2, V3), VIC blocks from $8400 (block 16), in this order:']
    lines += [';   %2d %s' % (16 + i, n) for i, (n, _) in enumerate(blocks)]
    lines.append('')
    for n, data in blocks:
        lines.append('        ; %s' % n)
        for i in range(0, 64, 16):
            lines.append('        .byte   ' + ','.join('$%02X' % v for v in data[i:i + 16]))
    with open(INC, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(os.path.relpath(INC, ROOT), len(blocks), 'sprites')


if __name__ == '__main__':
    main()
